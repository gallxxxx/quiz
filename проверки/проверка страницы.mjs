// Проверка страницы в jsdom: открываем её так же, как телефон, и жмём
// то же, что нажмёт человек. Ни один из багов прошлых недель линтером не
// ловился — они все были синтаксически безупречны.
import fs from "node:fs";
import { JSDOM } from "jsdom";

const ФАЙЛ = new URL("../index.html", import.meta.url);
const ошибки = [];
let сделано = 0;
const так = (что, условие, чего) => {
  сделано += 1;
  if (условие) console.log("  ок   " + что);
  else { ошибки.push(что + (чего ? " — " + чего : "")); console.log("  МИМО " + что); }
};

// Сток подменяем: нам важно, что делает страница, а не что отдаёт Pexels.
const снимок = (n) => ({
  показ: "https://пример/мал-" + n + ".jpg",
  ссылка: "https://пример/большой-" + n + ".jpg",
  вид: "фото", автор: "кто-то", источник: "Pexels", страница: "",
});
let запросовКСтоку = 0;
const фейкFetch = async (адрес) => {
  запросовКСтоку += 1;
  const строка = String(адрес);
  if (строка.includes("pexels")) {
    return { ok: true, status: 200, json: async () => ({
      photos: [1, 2, 3].map((n) => ({
        src: { medium: "https://пример/мал-" + n + ".jpg",
               large: "https://пример/большой-" + n + ".jpg" },
        photographer: "кто-то", url: "" })) }) };
  }
  if (строка.includes("openverse")) {
    return { ok: true, status: 200, json: async () => ({ results: [] }) };
  }
  return { ok: false, status: 404, json: async () => ({}) };
};

const html = fs.readFileSync(ФАЙЛ, "utf8");
const приставка = `
<script>
window.__жалобы = [];
window.addEventListener("error", (e) => window.__жалобы.push(String(e.message)));
</script>`;
const хвост = `
<script>
// Отсюда видно всё, что объявлено на странице: скрипты делят область.
window.__дай = {
  открытьЭкран: (что) => открытьЭкран(что),
  поставитьВыпуск: (в) => { q10 = в; q10Работы = [в]; },
  выпуск: () => q10,
  строки: (поле) => строки(поле),
  чтоНаКартинке: (i) => q10ЧтоНаКартинке(i),
  авто: () => q10Авто,
  кэшЧей: () => q10КэшЧей,
};
</script>`;

const страница = html.replace("</head>", приставка + "</head>")
                     .replace("</body>", хвост + "</body>");

const dom = new JSDOM(страница, {
  runScripts: "dangerously",
  url: "https://gallxxxx.github.io/quiz/",
  pretendToBeVisual: true,
  beforeParse(окно) {
    окно.fetch = фейкFetch;
    // Без ключа Pexels страница спрашивает только Openverse — и права,
    // что спрашивает. Нам надо проверить обычный случай, с ключом.
    окно.localStorage.setItem("викторина-доступ",
      JSON.stringify({ pexels: "ключ-для-проверки", токен: "" }));
    окно.HTMLMediaElement.prototype.play = function () {
      this.dispatchEvent(new окно.Event("playing"));
      return Promise.resolve();
    };
    окно.HTMLMediaElement.prototype.pause = () => {};
    окно.alert = (т) => окно.__жалобы.push("alert: " + String(т).slice(0, 60));
  },
});
const окно = dom.window;
const $ = (id) => окно.document.getElementById(id);
const ждать = (мс) => new Promise((г) => setTimeout(г, мс));
await ждать(300);

console.log("\n1. Страница открылась");
так("ошибок при загрузке нет", окно.__жалобы.length === 0,
    JSON.stringify(окно.__жалобы));
так("панель викторин на месте", !!$("q10-слоты") && !!$("voice"));

console.log("\n2. Голос можно послушать во всех трёх викторинах");
для_каждой: {
  так("кнопка у «Это или то»", !!$("voice-слушать"));
  так("кнопка у викторины на 10 пунктов", !!$("q10-голос-слушать"));
  так("кнопка у теста для пар", !!$("пары-голос-слушать"));
}
$("voice").value = "en-US-AriaNeural";
$("voice-слушать").dispatchEvent(new окно.Event("click", { bubbles: true }));
await ждать(60);
так("нажатие не роняет страницу", окно.__жалобы.length === 0,
    JSON.stringify(окно.__жалобы));
$("voice").value = "";
$("voice-слушать").dispatchEvent(new окно.Event("click", { bubbles: true }));
await ждать(40);
так("«без голоса» объясняется словами",
    /немым/.test($("voice-весть").textContent), $("voice-весть").textContent);

console.log("\n2б. Звук отсчёта у теста для пар");
так("список звуков появился", !!$("пары-звук"));
так("и его можно послушать", !!$("пары-звук-слушать"));
$("пары-звук").value = "тишина";
$("пары-звук-слушать").dispatchEvent(new окно.Event("click", { bubbles: true }));
await ждать(40);
так("«тишина» объяснена словами",
    /молча/.test($("пары-звук-весть").textContent),
    $("пары-звук-весть").textContent);
$("пары-звук").value = "часы";
$("пары-звук-слушать").dispatchEvent(new окно.Event("click", { bubbles: true }));
await ждать(40);
так("выбор звука не роняет страницу", окно.__жалобы.length === 0,
    JSON.stringify(окно.__жалобы));

console.log("\n3. Обложки делятся на сколько нужно");
$("пары-обложки").value =
  "Проверим, как хорошо вы знаете друг друга. Отвечайте вслух. Кто ответит точнее?";
$("пары-обложки").dispatchEvent(new окно.Event("input", { bubbles: true }));
так("сначала одна обложка", окно.__дай.строки("пары-обложки").length === 1);
так("счётчик показывает столько же",
    $("пары-обложек-сколько").textContent === "1");
$("пары-обложек-больше").dispatchEvent(new окно.Event("click", { bubbles: true }));
await ждать(30);
const после = окно.__дай.строки("пары-обложки");
так("стало две обложки", после.length === 2, JSON.stringify(после));
const слов = (т) => т.replace(/[.!?…\s]+/g, " ").trim().toLowerCase();
так("текст не потерялся и не дописался",
    слов(после.join(" ")) === слов("Проверим, как хорошо вы знаете друг друга."
      + " Отвечайте вслух. Кто ответит точнее?"), после.join(" | "));
$("пары-обложек-больше").dispatchEvent(new окно.Event("click", { bubbles: true }));
$("пары-обложек-больше").dispatchEvent(new окно.Event("click", { bubbles: true }));
await ждать(30);
так("больше, чем предложений, не делает",
    окно.__дай.строки("пары-обложки").length === 3,
    JSON.stringify(окно.__дай.строки("пары-обложки")));
так("и говорит об этом словами",
    /всего 3/.test($("пары-обложек-весть").textContent),
    $("пары-обложек-весть").textContent);
$("пары-обложек-меньше").dispatchEvent(new окно.Event("click", { bubbles: true }));
$("пары-обложек-меньше").dispatchEvent(new окно.Event("click", { bubbles: true }));
await ждать(30);
так("и обратно собирается в одну",
    окно.__дай.строки("пары-обложки").length === 1,
    JSON.stringify(окно.__дай.строки("пары-обложки")));

console.log("\n4. Экран картинок: видно, что подберётся само");
окно.__дай.поставитьВыпуск({
  ид: "2026-09-19T20-00-00", вид: "пары", имя: "тест",
  этап: "перевод", есть: "перевод",
  вопросы: ["What is her favorite flower?", "How tall is she?"],
  русские: ["Какой её любимый цветок?", "Какого она роста?"],
  ответы: [
    { ответ: "bouquet of flowers", вопрос: "What is her favorite flower?",
      русский: "Какой её любимый цветок?", картинка_рус: "букет цветов" },
    { ответ: "measuring tape height", вопрос: "How tall is she?",
      русский: "Какого она роста?", картинка_рус: "сантиметровая лента" },
  ],
  картинки: [],
});
запросовКСтоку = 0;
окно.__дай.открытьЭкран("q10pics");
await ждать(500);
const слоты = $("q10-слоты");
так("строк столько же, сколько вопросов",
    слоты.querySelectorAll(".card").length === 2);
const первая = слоты.querySelector(".card");
так("русский вопрос виден",
    /Какой её любимый цветок/.test(первая.textContent), первая.textContent);
так("написано, что будет на картинке",
    /на картинке: букет цветов/.test(первая.textContent), первая.textContent);
так("и обещано именно то, что подберётся",
    /подберётся эта/.test(первая.textContent), первая.textContent);
const фон = первая.querySelector(".превьюшка").style.backgroundImage;
так("в строке стоит миниатюра найденного",
    фон.includes("мал-1.jpg"), фон);
так("сток спрошен, но не завален",
    запросовКСтоку > 0 && запросовКСтоку <= 8, String(запросовКСтоку));
так("ошибок по дороге нет", окно.__жалобы.length === 0,
    JSON.stringify(окно.__жалобы));

console.log("\n5. Чужой выпуск не приносит чужие картинки");
так("кэш помечен этим выпуском",
    окно.__дай.кэшЧей() === "2026-09-19T20-00-00", String(окно.__дай.кэшЧей()));
окно.__дай.поставитьВыпуск({
  ид: "другой-выпуск", вид: "пары", имя: "второй",
  этап: "перевод", есть: "перевод",
  вопросы: ["Where did we first meet?"], русские: ["Где мы впервые встретились?"],
  ответы: [{ ответ: "couple in cafe", вопрос: "Where did we first meet?",
             русский: "Где мы впервые встретились?", картинка_рус: "пара в кафе" }],
  картинки: [],
});
окно.__дай.открытьЭкран("q10pics");
await ждать(40);      // сразу после открытия, до ответа стока
так("кэш сброшен на новый выпуск",
    окно.__дай.кэшЧей() === "другой-выпуск", String(окно.__дай.кэшЧей()));
так("строка одна, чужие не остались",
    $("q10-слоты").querySelectorAll(".card").length === 1);

console.log("\n6. Викторина на 10 пунктов: подпись из русского ответа");
окно.__дай.поставитьВыпуск({
  ид: "викторина-1", вид: "викторина", имя: "страны",
  этап: "перевод", есть: "перевод",
  текст: 'Т Правильный ответ. «Япония».\nТ Правильный ответ. «Бразилия».',
  ответы: [{ ответ: "Japan", время: "0:05" }, { ответ: "Brazil", время: "0:12" }],
  картинки: [],
});
окно.__дай.открытьЭкран("q10pics");
await ждать(400);
const строкаВикторины = $("q10-слоты").querySelector(".card");
так("русский ответ подписан как содержимое картинки",
    /на картинке: Япония/.test(строкаВикторины.textContent),
    строкаВикторины.textContent);
так("ошибок нет и здесь", окно.__жалобы.length === 0,
    JSON.stringify(окно.__жалобы));

console.log("\n———");
console.log(ошибки.length
  ? "НЕ СОШЛОСЬ (" + ошибки.length + " из " + сделано + "):\n  " + ошибки.join("\n  ")
  : "Сошлось всё: " + сделано + " проверок.");
dom.window.close();
process.exit(ошибки.length ? 1 : 0);
