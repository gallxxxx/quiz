// Отправка ролика: что происходит, когда сеть зависает.
//
// Ровно та жалоба Вики — «ролик отправляется уже очень долго» — и она
// была не про медленный интернет, а про то, что у запроса не было срока.
import fs from "node:fs";
import { JSDOM } from "jsdom";

const ФАЙЛ = new URL("../index.html", import.meta.url);
const ошибки = [];
let сделано = 0;
const так = (что, условие, чего) => {
  сделано += 1;
  if (условие) console.log("  ок   " + что);
  else { ошибки.push(что + (чего ? " — " + чего : "")); console.log("  МИМО " + что); }
};

const html = fs.readFileSync(ФАЙЛ, "utf8");
const хвост = `
<script>
window.__жалобы = [];
window.addEventListener("error", (e) => window.__жалобы.push(String(e.message)));
window.__дай = {
  разобрать: () => q10Разобрать(),
  файл: (ф) => { q10Файл = ф; },
  выпуск: () => q10,
  работы: () => q10Работы,
  поставитьПары: (в) => { q10 = в; q10Работы.unshift(в); },
  открытьЭкран: (что) => открытьЭкран(что),
};
</script>`;

// ——— поддельный XMLHttpRequest ———
// Он умеет главное: зависать. Настоящий браузер в этом случае ждёт
// молча, и до сегодняшней правки страница ждала вместе с ним.
const журнал = [];
let зависатьРаз = 0;          // сколько ближайших записей «повиснут»
const сделатьXHR = (окно) => class {
  constructor() { this.upload = {}; this.timeout = 0; this.status = 0; }
  open(метод, адрес) { this.метод = метод; this.адрес = адрес; }
  setRequestHeader() {}
  send(тело) {
    журнал.push({ метод: this.метод, адрес: this.адрес,
                  срок: this.timeout, байт: (тело || "").length });
    const зависнет = this.метод !== "GET" && зависатьРаз > 0;
    if (зависнет) зависатьРаз -= 1;
    // Прогресс и ответ приходят РАЗНЫМИ тиками — как в жизни. В одном
    // тике страница не успевает перерисоваться, и проверка «видно ли
    // проценты» проверяла бы саму заглушку, а не страницу.
    if (!зависнет && this.upload.onprogress) {
      for (const [задержка, доля] of [[5, 0.4], [15, 1]]) {
        окно.setTimeout(() => this.upload.onprogress({
          lengthComputable: true,
          loaded: Math.round((тело || "").length * доля),
          total: (тело || "").length || 1,
        }), задержка);
      }
    }
    окно.setTimeout(() => {
      if (зависнет) {
        // Так ведёт себя настоящий XHR, когда вышел срок.
        если_есть(this.ontimeout);
        return;
      }
      const адрес = this.адрес;
      if (this.метод === "GET" && /git\/ref\/heads\/main/.test(адрес)) {
        this.status = 200;
        this.responseText = JSON.stringify({ object: { sha: "abc123" } });
      } else if (this.метод === "GET") {
        this.status = 404;
        this.responseText = "{}";
      } else {
        this.status = 201;
        this.responseText = JSON.stringify({ content: { sha: "def456" } });
      }
      если_есть(this.onload);
    }, 30);
    const если_есть = (ф) => { if (ф) ф.call(this, {}); };
  }
};

const dom = new JSDOM(html.replace("</body>", хвост + "</body>"), {
  runScripts: "dangerously",
  url: "https://gallxxxx.github.io/quiz/",
  pretendToBeVisual: true,
  beforeParse(окно) {
    окно.localStorage.setItem("викторина-доступ",
      JSON.stringify({ pexels: "к", токен: "ghp_testtoken1234567890" }));
    окно.XMLHttpRequest = сделатьXHR(окно);
    окно.fetch = async () => ({ ok: false, status: 404, json: async () => ({}) });
    окно.alert = (т) => окно.__жалобы.push("alert: " + String(т).slice(0, 80));
    окно.confirm = () => false;
  },
});
const окно = dom.window;
const $ = (id) => окно.document.getElementById(id);
const ждать = (мс) => new Promise((г) => setTimeout(г, мс));
await ждать(300);

// Ролик на 3.3 МБ — ровно как у Вики: один кусок, порог 4 МБ.
const кусок = new окно.Uint8Array(3.3 * 1024 * 1024);
const файл = new окно.File([кусок], "v24025gl0000d37sp5nog65pci871oug.mp4",
                           { type: "video/mp4" });

console.log("\n1. У каждого запроса есть срок");
окно.__дай.файл(файл);
окно.__дай.открытьЭкран("q10start");
const шаги = [];
const следить = setInterval(() => {
  const т = $("q10-выбран").textContent.trim();
  if (т && шаги[шаги.length - 1] !== т) шаги.push(т);
}, 5);
await окно.__дай.разобрать();
clearInterval(следить);

const записи = журнал.filter((з) => з.метод !== "GET");
так("срок выставлен у всех запросов", журнал.every((з) => з.срок > 0),
    JSON.stringify(журнал.map((з) => з.срок)));
так("чтение ждёт не дольше полуминуты",
    журнал.filter((з) => з.метод === "GET").every((з) => з.срок <= 30000));
const файловый = записи.find((з) => з.байт > 1000000);
так("файлу срок дан по его размеру",
    !!файловый && файловый.срок > 60000 && файловый.срок < 600000,
    файловый ? String(файловый.срок) : "записи с файлом нет");

console.log("\n2. Видно, что происходит, а не «Отправляю…» в пустоту");
так("сказано до того, как пошла сеть",
    шаги.some((т) => /Готовлю место/.test(т)), JSON.stringify(шаги.slice(0, 3)));
так("показаны проценты отправки",
    шаги.some((т) => /Отправляю ролик: \d+%/.test(т)),
    JSON.stringify(шаги.filter((т) => /Отправляю/.test(т)).slice(0, 4)));
так("в конце сказано, что ролик уехал",
    шаги.some((т) => /Ролик отправлен/.test(т)), JSON.stringify(шаги.slice(-2)));
так("ошибок на странице нет", окно.__жалобы.length === 0,
    JSON.stringify(окно.__жалобы));

console.log("\n3. Зависшая сеть больше не останавливает отправку навсегда");
журнал.length = 0;
зависатьРаз = 2;            // первые две записи «повиснут» по сроку
окно.__дай.файл(new окно.File([new окно.Uint8Array(1024)], "второй.mp4",
                              { type: "video/mp4" }));
const начало = Date.now();
await окно.__дай.разобрать();
const прошло = Date.now() - начало;
const записи2 = журнал.filter((з) => з.метод !== "GET");
так("зависшие запросы повторились, а не встали",
    записи2.length >= 3, "записей: " + записи2.length);
так("выпуск всё-таки уехал",
    /Ролик отправлен/.test($("q10-выбран").textContent),
    $("q10-выбран").textContent);
так("и это не заняло вечность", прошло < 20000, прошло + " мс");
так("работ в списке две, вторая не затёрла первую",
    окно.__дай.работы().length === 2, String(окно.__дай.работы().length));

console.log("\n4. Чтение всегда свежее, а кнопки обложек честные");
const чтения = журнал.filter((з) => з.метод === "GET");
так("у каждого чтения свой адрес — кэшу нечего вернуть",
    чтения.length > 1
    && new Set(чтения.map((з) => з.адрес)).size === чтения.length,
    "адресов " + new Set(чтения.map((з) => з.адрес)).size
      + " на " + чтения.length + " чтений");
так("обход кэша виден в адресе",
    чтения.every((з) => /[?&]_=\d+/.test(з.адрес)),
    чтения[0] && чтения[0].адрес);

// Экран «проверь текст» до того, как машина прислала разбор.
окно.__дай.поставитьПары({ ид: "ждём-разбора", вид: "пары", имя: "ждёт",
                           этап: "расшифровка" });
окно.__дай.открытьЭкран("парытекст");
await ждать(40);
так("счётчик показывает ноль обложек, а не единицу из разметки",
    $("пары-обложек-сколько").textContent === "0",
    $("пары-обложек-сколько").textContent);
так("кнопки «−» и «+» серые, пока делить нечего",
    $("пары-обложек-меньше").disabled && $("пары-обложек-больше").disabled);
так("и сказано, почему",
    /делить нечего/.test($("пары-обложек-весть").textContent),
    $("пары-обложек-весть").textContent);

$("пары-обложки").value = "Первое предложение. Второе предложение.";
$("пары-обложки").dispatchEvent(new окно.Event("input", { bubbles: true }));
await ждать(20);
так("с текстом «+» оживает", !$("пары-обложек-больше").disabled);
так("«−» на одной обложке всё ещё серая", $("пары-обложек-меньше").disabled);
$("пары-обложек-больше").dispatchEvent(new окно.Event("click", { bubbles: true }));
await ждать(20);
так("после деления на два «−» оживает", !$("пары-обложек-меньше").disabled);
так("а «+» гаснет: предложений всего два", $("пары-обложек-больше").disabled);

console.log("\n———");
console.log(ошибки.length
  ? "НЕ СОШЛОСЬ (" + ошибки.length + " из " + сделано + "):\n  " + ошибки.join("\n  ")
  : "Сошлось всё: " + сделано + " проверок.");
окно.close();
process.exit(ошибки.length ? 1 : 0);
